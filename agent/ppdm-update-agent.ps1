#requires -Version 5.1
<#
.SYNOPSIS
    Loopback update helper for the PikPak Dark Mode theme.

.DESCRIPTION
    The theme runs inside PikPak's renderer, which cannot write files. This
    helper is the small privileged bridge the in-app updater talks to:

        renderer  --(delta files, SHA-256 verified)-->  agent  -->  disk

    It only binds 127.0.0.1, it never contacts the network, and it only writes
    pikpak-darkmode* files inside the theme folder it was installed for. Every
    accepted file is checked against the SHA-256 the browser already verified,
    the previous files are backed up, and each replacement is written to a
    temporary file before being moved into place.

    apply-darkmode.ps1 installs it under %LOCALAPPDATA%\PikPak-DarkMode and
    registers it for the current user, so no administrator rights are needed
    for the helper itself. When PikPak lives in Program Files, the final copy
    is delegated to a single elevated child process (one Windows prompt).

.PARAMETER Port
    Loopback port. Read from agent.json when omitted.

.PARAMETER ApplyStaged
    Internal: apply an already staged update. Used by the elevated child.

.PARAMETER StagedDir
    Folder holding staged files for -ApplyStaged.

.PARAMETER Stop
    Stops the helper that agent.json points at, then exits.

.PARAMETER Status
    Prints the helper state and exits.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\agent\ppdm-update-agent.ps1 -Status

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\agent\ppdm-update-agent.ps1 -Stop
#>
[CmdletBinding()]
param(
    [int]$Port = 0,
    [switch]$ApplyStaged,
    [string]$StagedDir,
    [switch]$Stop,
    [switch]$Status
)

$ErrorActionPreference = 'Stop'

$AgentVersion = '1.0.0'
$AgentHome    = Join-Path $env:LOCALAPPDATA 'PikPak-DarkMode'
if (-not $env:LOCALAPPDATA) { $AgentHome = Join-Path $env:APPDATA 'PikPak-DarkMode' }
$ConfigPath   = Join-Path $AgentHome 'agent.json'
$LogPath      = Join-Path $AgentHome 'agent.log'
$StatePath    = Join-Path $AgentHome 'state.json'
$BackupRoot   = Join-Path $AgentHome 'backups'
$StageRoot    = Join-Path $AgentHome 'staging'
$VersionFile  = 'pikpak-darkmode.version.js'

# Only theme assets may be written, and only ever inside the theme folder.
$AllowedName = '^pikpak-darkmode[a-z0-9.-]*\.(?:css|js)$'
$MaxBodyBytes = 16MB

function Write-AgentLog([string]$Message) {
    try {
        if (-not (Test-Path -LiteralPath $AgentHome)) {
            New-Item -ItemType Directory -Force -Path $AgentHome | Out-Null
        }
        if ((Test-Path -LiteralPath $LogPath) -and ((Get-Item -LiteralPath $LogPath).Length -gt 262144)) {
            Remove-Item -LiteralPath $LogPath -Force -ErrorAction SilentlyContinue
        }
        $line = '[{0}] {1}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Message
        Add-Content -LiteralPath $LogPath -Value $line -Encoding UTF8
    } catch { }
}

function Get-AgentConfig {
    if (-not (Test-Path -LiteralPath $ConfigPath)) { return $null }
    try {
        $raw = Get-Content -LiteralPath $ConfigPath -Raw
        return ($raw | ConvertFrom-Json)
    } catch {
        return $null
    }
}

function Save-AgentConfig($Config) {
    if (-not (Test-Path -LiteralPath $AgentHome)) {
        New-Item -ItemType Directory -Force -Path $AgentHome | Out-Null
    }
    $json = $Config | ConvertTo-Json -Depth 6
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($ConfigPath, $json, $utf8)
}

function Set-ConfigValue($Config, [string]$Name, $Value) {
    if ($Config.PSObject.Properties[$Name]) {
        $Config.$Name = $Value
    } else {
        $Config | Add-Member -NotePropertyName $Name -NotePropertyValue $Value -Force
    }
}

function Test-ThemeWritable([string]$ThemeDir) {
    if (-not $ThemeDir -or -not (Test-Path -LiteralPath $ThemeDir)) { return $false }
    $probe = Join-Path $ThemeDir '.ppdm-write-probe'
    try {
        [System.IO.File]::WriteAllText($probe, 'probe')
        Remove-Item -LiteralPath $probe -Force
        return $true
    } catch {
        return $false
    }
}

function Get-Sha256Hex([byte[]]$Bytes) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $hash = $sha.ComputeHash($Bytes)
        return (-join ($hash | ForEach-Object { $_.ToString('x2') }))
    } finally {
        $sha.Dispose()
    }
}

function Write-VersionFile([string]$ThemeDir, $Manifest) {
    $entries = @()
    foreach ($property in $Manifest.files.PSObject.Properties) {
        $entry = $property.Value
        $entries += '    "{0}": {{ "sha256": "{1}", "size": {2} }}' -f $property.Name, [string]$entry.sha256, [int]$entry.size
    }
    $fileEntries = $entries -join ",`r`n"

    $content = @"
/*!
 * PikPak Dark Mode - installed version manifest
 * Generated by the update helper - do not edit by hand.
 */
window.PIKPAK_DARKMODE_VERSION = {
  "version": "$([string]$Manifest.version)",
  "bootstrap": $([int]$Manifest.bootstrap),
  "released": "$([string]$Manifest.released)",
  "files": {
$fileEntries
  }
};
"@

    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText((Join-Path $ThemeDir $VersionFile), ($content -replace "`r?`n", "`r`n"), $utf8)
}

function Install-ThemeFiles {
    param(
        [Parameter(Mandatory = $true)][string]$FilesDir,
        [Parameter(Mandatory = $true)]$Manifest,
        [Parameter(Mandatory = $true)][string]$ThemeDir
    )

    if (-not (Test-Path -LiteralPath $ThemeDir)) {
        return @{ Ok = $false; Error = 'theme-missing' }
    }
    if (-not (Test-ThemeWritable $ThemeDir)) {
        return @{ Ok = $false; NeedsElevation = $true }
    }

    # Timestamped backup of the files we are about to replace.
    try {
        $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
        $backupDir = Join-Path $BackupRoot ('{0}-v{1}' -f $stamp, $Manifest.version)
        New-Item -ItemType Directory -Force -Path $backupDir | Out-Null
        Get-ChildItem -LiteralPath $ThemeDir -File -Filter 'pikpak-darkmode*' -ErrorAction SilentlyContinue |
            ForEach-Object { Copy-Item -LiteralPath $_.FullName -Destination (Join-Path $backupDir $_.Name) -Force }
    } catch {
        Write-AgentLog ("backup skipped: {0}" -f $_.Exception.Message)
    }

    $applied = New-Object System.Collections.Generic.List[string]
    # staged.manifest.json is bookkeeping for the elevated child, not an asset.
    foreach ($file in (Get-ChildItem -LiteralPath $FilesDir -File | Where-Object { $_.Name -ne 'staged.manifest.json' })) {
        $destination = Join-Path $ThemeDir $file.Name
        $temp = Join-Path $ThemeDir ('.ppdm-' + $file.Name + '.tmp')
        [System.IO.File]::Copy($file.FullName, $temp, $true)
        if (Test-Path -LiteralPath $destination) {
            Remove-Item -LiteralPath $destination -Force
        }
        Move-Item -LiteralPath $temp -Destination $destination -Force
        $applied.Add($file.Name)
    }

    Write-VersionFile -ThemeDir $ThemeDir -Manifest $Manifest

    $state = @{
        version   = [string]$Manifest.version
        files     = @($applied)
        updatedAt = (Get-Date).ToString('o')
        themeDir  = $ThemeDir
    }
    if (-not (Test-Path -LiteralPath $AgentHome)) {
        New-Item -ItemType Directory -Force -Path $AgentHome | Out-Null
    }
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($StatePath, ($state | ConvertTo-Json -Depth 6), $utf8)

    Write-AgentLog ("installed v{0} ({1} files) into {2}" -f $Manifest.version, $applied.Count, $ThemeDir)
    return @{ Ok = $true; Files = @($applied) }
}

function Invoke-ElevatedInstall {
    param(
        [Parameter(Mandatory = $true)][string]$FilesDir,
        [Parameter(Mandatory = $true)][string]$ThemeDir
    )

    $psExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
    $arguments = '-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File "{0}" -ApplyStaged -StagedDir "{1}"' -f
        $PSCommandPath, $FilesDir

    # The staged folder carries its manifest, so the child needs nothing else.
    try {
        $process = Start-Process -FilePath $psExe -ArgumentList $arguments -Verb RunAs -PassThru -Wait -WindowStyle Hidden
        if ($process.ExitCode -eq 0) { return @{ Ok = $true; Elevated = $true } }
        return @{ Ok = $false; Error = 'elevation-failed' }
    } catch {
        Write-AgentLog ("elevation cancelled: {0}" -f $_.Exception.Message)
        return @{ Ok = $false; Error = 'elevation-cancelled' }
    }
}

function Restart-PikPak($Config) {
    try {
        $exe = [string]$Config.exe
        if (-not $exe -and $Config.installDir) { $exe = Join-Path ([string]$Config.installDir) 'PikPak.exe' }
        $running = Get-Process -Name 'PikPak' -ErrorAction SilentlyContinue
        if ($running) {
            $running | Stop-Process -Force
            Start-Sleep -Milliseconds 900
        }
        if ($exe -and (Test-Path -LiteralPath $exe)) {
            Start-Process -FilePath $exe | Out-Null
            Write-AgentLog 'PikPak restarted'
        }
    } catch {
        Write-AgentLog ("restart failed: {0}" -f $_.Exception.Message)
    }
}

