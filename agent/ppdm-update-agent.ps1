function Send-CorsHeaders($Context) {
    $headers = $Context.Response.Headers
    $headers['Access-Control-Allow-Origin'] = '*'
    $headers['Access-Control-Allow-Methods'] = 'GET, POST, OPTIONS'
    $headers['Access-Control-Allow-Headers'] = 'content-type'
    $headers['Access-Control-Allow-Private-Network'] = 'true'
    $headers['Cache-Control'] = 'no-store'
    $headers['X-Content-Type-Options'] = 'nosniff'
}

function Send-Json($Context, [int]$StatusCode, $Payload) {
    $json = $Payload | ConvertTo-Json -Depth 12 -Compress
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($json)
    Send-CorsHeaders $Context
    $Context.Response.StatusCode = $StatusCode
    $Context.Response.ContentType = 'application/json; charset=utf-8'
    $Context.Response.ContentLength64 = $bytes.Length
    try { $Context.Response.OutputStream.Write($bytes, 0, $bytes.Length) } catch { }
    try { $Context.Response.OutputStream.Close() } catch { }
    try { $Context.Response.Close() } catch { }
}

function Send-Empty($Context, [int]$StatusCode = 204) {
    Send-CorsHeaders $Context
    $Context.Response.StatusCode = $StatusCode
    $Context.Response.ContentLength64 = 0
    try { $Context.Response.Close() } catch { }
}

function Receive-Apply($Context, $Config) {
    if ($Context.Request.ContentLength64 -gt $MaxBodyBytes) {
        Send-Json $Context 413 @{ ok = $false; error = 'too-large' }
        return
    }

    $reader = New-Object System.IO.StreamReader($Context.Request.InputStream, [System.Text.Encoding]::UTF8)
    $raw = $reader.ReadToEnd()
    $reader.Close()

    $body = $null
    try { $body = $raw | ConvertFrom-Json } catch { $body = $null }
    if (-not $body) {
        Send-Json $Context 400 @{ ok = $false; error = 'bad-json' }
        return
    }
    if (-not $Config.token -or [string]$body.token -ne [string]$Config.token) {
        Send-Json $Context 403 @{ ok = $false; error = 'unauthorized' }
        return
    }

    $version = [string]$body.version
    if ($version -notmatch '^\d+(?:\.\d+){0,3}(?:-[0-9A-Za-z.]+)?$') {
        Send-Json $Context 400 @{ ok = $false; error = 'bad-version' }
        return
    }
    if (-not $body.manifest -or -not $body.manifest.files) {
        Send-Json $Context 400 @{ ok = $false; error = 'bad-manifest' }
        return
    }

    $themeDir = [string]$Config.themeDir
    if (-not $themeDir -or -not (Test-Path -LiteralPath $themeDir)) {
        Send-Json $Context 400 @{ ok = $false; error = 'theme-missing' }
        return
    }

    # A release can legitimately change no assets (notes only). The version
    # manifest still has to be rewritten, so an empty file set is accepted.
    $files = @($body.files)

    $filesDir = Join-Path $StageRoot $version
    if (Test-Path -LiteralPath $filesDir) { Remove-Item -LiteralPath $filesDir -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $filesDir | Out-Null

    foreach ($file in $files) {
        $name = [string]$file.name
        if ($name -notmatch $AllowedName) {
            Send-Json $Context 400 @{ ok = $false; error = 'bad-name' }
            return
        }
        try {
            $bytes = [Convert]::FromBase64String([string]$file.data)
        } catch {
            Send-Json $Context 400 @{ ok = $false; error = 'bad-payload' }
            return
        }
        if ($bytes.Length -eq 0 -or $bytes.Length -gt 8MB) {
            Send-Json $Context 400 @{ ok = $false; error = 'bad-size' }
            return
        }
        $digest = Get-Sha256Hex $bytes
        $expected = ([string]$file.sha256).ToLowerInvariant()
        if ($expected -and $digest -ne $expected) {
            Send-Json $Context 400 @{ ok = $false; error = 'hash-mismatch' }
            return
        }
        [System.IO.File]::WriteAllBytes((Join-Path $filesDir $name), $bytes)
    }

    # The elevated child reads the manifest from the staged folder.
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText(
        (Join-Path $filesDir 'staged.manifest.json'),
        ($body.manifest | ConvertTo-Json -Depth 12),
        $utf8
    )

    $result = Install-ThemeFiles -FilesDir $filesDir -Manifest $body.manifest -ThemeDir $themeDir
    if (-not $result.Ok -and $result.NeedsElevation) {
        $result = Invoke-ElevatedInstall -FilesDir $filesDir -ThemeDir $themeDir
    }
    if (-not $result.Ok) {
        Send-Json $Context 400 @{ ok = $false; error = $result.Error }
        return
    }

    Send-Json $Context 200 @{
        ok       = $true
        version  = $version
        elevated = [bool]$result.Elevated
        files    = @($result.Files)
    }

    if ($body.restart) {
        Start-Sleep -Milliseconds 350
        Restart-PikPak $Config
    }
}

function Start-Agent($Config) {
    if (Test-Path -LiteralPath $StatePath) { } # state is read by diagnostics only

    $prefix = 'http://127.0.0.1:{0}/' -f $Config.port
    $listener = New-Object System.Net.HttpListener
    $listener.Prefixes.Add($prefix)
    try {
        $listener.Start()
    } catch {
        Write-AgentLog ("could not bind {0}: {1}" -f $prefix, $_.Exception.Message)
        exit 1
    }

    Write-AgentLog ("agent {0} listening on {1} (theme: {2})" -f $AgentVersion, $prefix, $Config.themeDir)

    while ($true) {
        $context = $null
        try {
            $context = $listener.GetContext()
        } catch {
            Write-AgentLog ("listener stopped: {0}" -f $_.Exception.Message)
            break
        }
        try {
            $method = $context.Request.HttpMethod.ToUpperInvariant()
            $path = $context.Request.Url.AbsolutePath

            if ($method -eq 'OPTIONS') {
                Send-Empty $context
            } elseif ($method -eq 'GET' -and $path -eq '/health') {
                Send-Json $context 200 @{
                    ok       = $true
                    agent    = $AgentVersion
                    themeDir = [string]$Config.themeDir
                    canWrite = (Test-ThemeWritable ([string]$Config.themeDir))
                }
            } elseif ($method -eq 'GET' -and $path -eq '/state') {
                $state = $null
                if (Test-Path -LiteralPath $StatePath) {
                    try { $state = Get-Content -LiteralPath $StatePath -Raw | ConvertFrom-Json } catch { $state = $null }
                }
                Send-Json $context 200 @{ ok = $true; state = $state }
            } elseif ($method -eq 'POST' -and $path -eq '/apply') {
                Receive-Apply $context $Config
            } else {
                Send-Json $context 404 @{ ok = $false; error = 'not-found' }
            }
        } catch {
            Write-AgentLog ("request failed: {0}" -f $_.Exception.Message)
            try { Send-Json $context 500 @{ ok = $false; error = 'agent-error' } } catch { }
        }
    }
}

# ---------------------------------------------------------------- #
# entry points                                                      #
# ---------------------------------------------------------------- #

if (-not (Test-Path -LiteralPath $AgentHome)) {
    New-Item -ItemType Directory -Force -Path $AgentHome | Out-Null
}

if ($ApplyStaged) {
    # Elevated child: apply the staged folder, then leave.
    if (-not $StagedDir -or -not (Test-Path -LiteralPath $StagedDir)) { exit 2 }
    $manifestPath = Join-Path $StagedDir 'staged.manifest.json'
    if (-not (Test-Path -LiteralPath $manifestPath)) { exit 3 }
    $config = Get-AgentConfig
    if (-not $config -or -not $config.themeDir) { exit 4 }
    try {
        $manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
        $result = Install-ThemeFiles -FilesDir $StagedDir -Manifest $manifest -ThemeDir ([string]$config.themeDir)
        if ($result.Ok) { exit 0 }
        exit 5
    } catch {
        Write-AgentLog ("elevated install failed: {0}" -f $_.Exception.Message)
        exit 6
    }
}

$config = Get-AgentConfig

if ($Stop) {
    if ($config -and $config.pid) {
        try {
            $process = Get-Process -Id ([int]$config.pid) -ErrorAction SilentlyContinue
            if ($process) {
                $process | Stop-Process -Force
                Write-Host 'Update helper stopped.' -ForegroundColor Green
            } else {
                Write-Host 'Update helper is not running.' -ForegroundColor Yellow
            }
        } catch {
            Write-Host 'Update helper is not running.' -ForegroundColor Yellow
        }
    } else {
        Write-Host 'No update helper configuration found.' -ForegroundColor Yellow
    }
    exit 0
}

if (-not $config) {
    Write-Host 'No agent.json found. Run apply-darkmode.ps1 first.' -ForegroundColor Red
    exit 1
}

if ($Status) {
    $alive = $false
    try {
        $response = Invoke-WebRequest -Uri ('http://127.0.0.1:{0}/health' -f $config.port) -UseBasicParsing -TimeoutSec 2
        $alive = ($response.StatusCode -eq 200)
    } catch { $alive = $false }

    Write-Host ''
    Write-Host 'PikPak Dark Mode update helper' -ForegroundColor Cyan
    Write-Host ('  Port        : {0}' -f $config.port)
    Write-Host ('  Theme folder: {0}' -f $config.themeDir)
    if ($alive) { Write-Host '  State       : running' -ForegroundColor Green }
    else { Write-Host '  State       : stopped' -ForegroundColor Yellow }
    Write-Host ('  Log         : {0}' -f $LogPath)
    Write-Host ''
    exit 0
}

if ($Port -gt 0) {
    Set-ConfigValue $config 'port' $Port
    Save-AgentConfig $config
}

if (-not $config.port) { Set-ConfigValue $config 'port' 48179 }
if (-not $config.themeDir) {
    Write-Host 'agent.json has no themeDir. Re-run apply-darkmode.ps1.' -ForegroundColor Red
    exit 1
}

Set-ConfigValue $config 'pid' $PID
Save-AgentConfig $config

Start-Agent $config
