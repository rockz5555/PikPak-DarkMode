#requires -Version 5.1
<#
.SYNOPSIS
    Builds the release manifest and the installed-version manifest.

.DESCRIPTION
    The updater never downloads a repository. It compares two manifests:

        update/manifest.json                  (what the latest release contains)
        theme/pikpak-darkmode.version.js      (what this machine has installed)

    Both are generated here, from the real files, so they cannot drift:
      * every theme asset gets a size and a SHA-256
      * pikpak-darkmode.version.js describes the installed set
      * update/manifest.json adds the changelog, bootstrap revision and schema

    Run this whenever the theme changes, then commit theme/ and update/.

.PARAMETER Version
    Release version, for example 1.1.0.

.PARAMETER Notes
    Changelog lines shown in the update card (max 3 are displayed).

.PARAMETER Bootstrap
    Loader revision written by apply-darkmode.ps1. Bump it when the injected
    block itself changes; the updater then nudges the user to re-run the
    installer once.

.EXAMPLE
    .\tools\build-update.ps1 -Version 1.1.0 -Notes 'Themed the transfer list','Faster first paint'

.EXAMPLE
    .\tools\build-update.ps1 -Version 1.2.0 -Bootstrap 2
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidatePattern('^\d+(\.\d+){1,3}(-[0-9A-Za-z.]+)?$')]
    [string]$Version,

    [string[]]$Notes = @(),

    [int]$Bootstrap = 3
)

$ErrorActionPreference = 'Stop'

$Root       = Split-Path -Parent $PSScriptRoot
$ThemeDir   = Join-Path $Root 'theme'
$UpdateDir  = Join-Path $Root 'update'
$VersionJs  = Join-Path $ThemeDir 'pikpak-darkmode.version.js'

$assets = @(
    'pikpak-darkmode.css',
    'pikpak-darkmode.js',
    'pikpak-darkmode-updater.css',
    'pikpak-darkmode-updater.js'
)

foreach ($name in $assets) {
    $path = Join-Path $ThemeDir $name
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Missing theme asset: $path"
    }
}

# GitHub serves the committed blobs with LF line endings. Normalize the local
# assets before hashing so the manifest describes the bytes the updater will
# actually download, even if an editor saved a file with CRLF.
$utf8 = New-Object System.Text.UTF8Encoding($false)
foreach ($name in $assets) {
    $path = Join-Path $ThemeDir $name
    $text = [System.IO.File]::ReadAllText($path)
    $normalized = $text -replace "`r`n", "`n"
    if ($text -ne $normalized) {
        [System.IO.File]::WriteAllText($path, $normalized, $utf8)
    }
}

$files = [ordered]@{}
foreach ($name in $assets) {
    $path = Join-Path $ThemeDir $name
    $item = Get-Item -LiteralPath $path
    $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    $files[$name] = [ordered]@{
        sha256 = $hash
        size   = [int]$item.Length
    }
}

$released = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd')

$fileEntries = ($files.Keys | ForEach-Object {
    $entry = $files[$_]
    '    "{0}": {{ "sha256": "{1}", "size": {2} }}' -f $_, $entry.sha256, $entry.size
}) -join ",`n"

$versionSource = @"
/*!
 * PikPak Dark Mode - installed version manifest
 * Generated by tools/build-update.ps1 - do not edit by hand.
 *
 * The in-app updater diffs this table against update/manifest.json and only
 * downloads the files whose SHA-256 differs.
 */
window.PIKPAK_DARKMODE_VERSION = {
  "version": "$Version",
  "bootstrap": $Bootstrap,
  "released": "$released",
  "files": {
$fileEntries
  }
};
"@

[System.IO.File]::WriteAllText($VersionJs, ($versionSource -replace "`r?`n", "`n"), $utf8)

if ($Notes.Count -gt 0) {
    $notesJson = "[`n" + (($Notes | ForEach-Object { '    "{0}"' -f $_ }) -join ",`n") + "`n  ]"
} else {
    $notesJson = '[]'
}

$manifestSource = @"
{
  "schema": 1,
  "version": "$Version",
  "bootstrap": $Bootstrap,
  "released": "$released",
  "notes": $notesJson,
  "files": {
$fileEntries
  }
}
"@

if (-not (Test-Path -LiteralPath $UpdateDir)) {
    New-Item -ItemType Directory -Force -Path $UpdateDir | Out-Null
}
$manifestPath = Join-Path $UpdateDir 'manifest.json'
[System.IO.File]::WriteAllText($manifestPath, ($manifestSource -replace "`r?`n", "`n"), $utf8)

Write-Host ''
Write-Host ('Release manifest built for v{0}' -f $Version) -ForegroundColor Green
foreach ($name in $files.Keys) {
    $entry = $files[$name]
    Write-Host ('  {0,-34} {1,7} bytes  {2}' -f $name, $entry.size, $entry.sha256.Substring(0, 12))
}
Write-Host ('  {0,-34} {1}' -f 'installed manifest:', (Split-Path -Leaf $VersionJs))
Write-Host ('  {0,-34} {1}' -f 'release manifest:', $manifestPath)
if ($Notes.Count -gt 0) {
    Write-Host '  notes:' -ForegroundColor DarkGray
    foreach ($note in $Notes) { Write-Host ('    - {0}' -f $note) -ForegroundColor DarkGray }
}
Write-Host ''
